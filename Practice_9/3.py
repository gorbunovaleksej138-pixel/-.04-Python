print("Расчет минимального количества монет для оплаты услуг ведьмака")

# Получаем сумму платежа
price = int(input("Сумма к оплате: "))

# Доступные номиналы монет (от больших к меньшим)
coins = [25, 10, 5, 1]
total_coins = 0  # Общее количество монет

# Идем от самых крупных монет к самым мелким
for coin in coins:
    # Сколько монет текущего номинала можно использовать
    count = price // coin
    total_coins += count  # Увеличиваем общее количество

    # Уменьшаем оставшуюся сумму
    price -= count * coin

# Выводим результат
print(f"Минимальное количество монет: {total_coins}")