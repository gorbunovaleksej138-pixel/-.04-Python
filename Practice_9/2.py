print("Определение количества людей между Александрой и Левоном в очереди")
# Инициализация переменных
count = 0  # Счетчик людей между Александрой и Левоном
found_alex = False  # Флаг, найден ли Александра

print("Вводите имена участников (пустая строка - завершение ввода):")

# Цикл для ввода имен
while True:
    name = input().strip()  # Получаем имя, убираем пробелы

    # Проверяем пустую строку для завершения ввода
    if name == "":
        break

    # Если нашли Александру
    if name == "Александра":
        found_alex = True
        continue  # Переходим к следующему имени

    # Если нашли Левона ПОСЛЕ Александры
    if name == "Левон" and found_alex:
        break  # Завершаем подсчет

    # Если Александра уже найдена, но Левон еще нет - считаем человека
    if found_alex:
        count += 1

# Вывод результата
print(f"Между Александрой и Левоном стоят {count} человек(а)")