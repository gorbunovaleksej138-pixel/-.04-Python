# Правильный пин-код
CORRECT_PIN = 4590

print("=== КОДОВЫЙ ЗАМОК ===")
print("Введите пин-код для доступа")

while True:  # Бесконечный цикл - эмуляция do-while
    # Запрашиваем ввод пин-кода
    try:
        entered_pin = int(input("\nВведите пин-код: "))
    except ValueError:
        print("Ошибка. Введите целое число.")
        continue  # Пропускаем некорректный ввод

    # Проверяем пин-код
    if entered_pin == CORRECT_PIN:
        print("Доступ разрешен")
        break  # Выход из цикла при правильном коде
    else:
        print("Ошибка. Попробуйте еще раз")
        # Цикл продолжится для следующей попытки

print("\nДверь открыта. Программа завершена.")
