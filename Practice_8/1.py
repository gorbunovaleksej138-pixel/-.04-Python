print("Таблица умножения на заданное число")
# Ввод числа от пользователя
n = int(input("Введите натуральное число n: "))

print(f"\nТаблица умножения на {n}:")
print("=" * 20)

# Цикл с параметром for для вывода таблицы умножения
for i in range(1, 11):  # i меняется от 1 до 10
    result = n * i
    print(f"{n} x {i} = {result}")

print("=" * 20)
