import random
import math

# — Константы
TITLE = 'Тык-тык'                      # Заголовок главного окна вашей игры
WIDTH = 800                            # Ширина игрового окна в пикселях
HEIGHT = 600                           # Высота игрового окна в пикселях
BACKGROUND_COLOR = (20, 30, 40)         # Темно-синий цвет фона в формате RGB
TEXT_COLOR = (220, 220, 220)             # Светло-серый цвет текста для текущего счета
SECONDARY_TEXT_COLOR = (200, 200, 200)   # Промежуточный серый цвет для вывода скорости
HINT_TEXT_COLOR = (180, 180, 200)        # Серо-сиреневый цвет для подсказки по лопанию
HELP_TEXT_COLOR = (160, 160, 180)        # Приглушенный цвет для меню перезапуска и выхода
GAMEOVER_TEXT_COLOR = (255, 100, 100)    # Ярко-красный цвет для финальной надписи окончания игры
MIN_SPEED = 1.0                        # Минимально возможная начальная скорость шарика
MAX_SPEED = 3.0                        # Максимально возможная начальная скорость шарика
MIN_CIRCLES = 9                        # Минимальное количество шариков, создаваемых на старте
MAX_CIRCLES = 18                       # Максимальное количество шариков, создаваемых на старте
MAX_SCORE = 25                         # Лимит набранных очков, при котором наступает победа


# — Класс Circle
class Circle:
    def __init__(self):
        """ Конструктор класса: инициализирует новый шарик со случайными свойствами """
        self.radius = random.randint(15, 35)  # Задает случайный радиус шарика от 15 до 35 пикселей
        # Генерирует случайный яркий цвет в формате RGB (каждый канал от 100 до 255)
        self.color = (random.randint(100, 255), random.randint(100, 255), random.randint(100, 255))
        # Выбирает случайную координату X так, чтобы шарик не появлялся за левой или правой границей
        self.x = random.randint(self.radius, WIDTH - self.radius)
        # Выбирает случайную координату Y так, чтобы шарик не появлялся за верхней или нижней границей
        self.y = random.randint(self.radius, HEIGHT - self.radius)
        speed = random.uniform(MIN_SPEED, MAX_SPEED)  # Выбирает случайную начальную скорость шарика
        angle = random.uniform(0, 2 * math.pi)  # Генерирует случайный угол направления движения в радианах
        self.dx = math.cos(angle) * speed  # Рассчитывает шаг смещения шарика по горизонтали (ось X)
        self.dy = math.sin(angle) * speed  # Рассчитывает шаг смещения шарика по вертикали (ось Y)
        self.is_popping = False  # Флаг состояния: лопается ли шарик в данный момент (True/False)
        self.pop_progress = 0.0  # Прогресс анимации лопания от 0.0 (целый) до 1.0 (полностью исчез)
        self.pop_speed = 0.2  # Скорость исчезновения шарика (увеличивает прогресс на 0.2 каждый кадр)

    def move(self, multiplier):
        """ Управляет движением шарика по экрану и его отскоками от границ окна """
        if self.is_popping:
            return  # Если шарик лопается, он застывает на месте и больше не двигается
        self.x += self.dx * multiplier  # Изменяет координату X с учетом текущего множителя скорости игры
        self.y += self.dy * multiplier  # Изменяет координату Y с учетом текущего множителя скорости игры

        # Проверка столкновения с левой границей экрана
        if self.x - self.radius < 0:
            self.x = self.radius  # Удерживает шарик в пределах экрана
            self.dx = -self.dx  # Разворачивает движение по горизонтали в обратную сторону
        # Проверка столкновения с правой границей экрана
        if self.x + self.radius > WIDTH:
            self.x = WIDTH - self.radius
            self.dx = -self.dx
        # Проверка столкновения с верхней границей экрана
        if self.y - self.radius < 0:
            self.y = self.radius
            self.dy = -self.dy  # Разворачивает движение по вертикали в обратную сторону
        # Проверка столкновения с нижней границей экрана
        if self.y + self.radius > HEIGHT:
            self.y = HEIGHT - self.radius
            self.dy = -self.dy

    def update(self):
        """ Обновляет стадию лопания шарика. Возвращает True, когда анимация полностью завершена """
        if not self.is_popping:
            return False  # Если по шарику еще не кликнули, анимация лопания не обновляется
        self.pop_progress += self.pop_speed  # Продвигает шкалу исчезновения вперед
        return self.pop_progress >= 1  # Возвращает True, если прогресс достиг конца (1.0 или больше)

    def draw(self):
        """ Отвечает за визуальное отображение шарика на игровом экране """
        if not self.is_popping:
            # Отрисовка целого шарика: цветной залитый круг внутри
            screen.draw.filled_circle((self.x, self.y), self.radius, self.color)
            # Тонкий белый контур вокруг шарика для лучшей видимости
            screen.draw.circle((self.x, self.y), self.radius, (255, 255, 255))
            return
        # Если шарик лопается, вычисляется его новый, уменьшенный радиус сдувания
        r = int(self.radius * (1 - self.pop_progress))
        if r < 1:
            r = 1  # Защита от ошибок: радиус круга для отрисовки не должен опускаться ниже 1 пикселя
        screen.draw.filled_circle((self.x, self.y), r, self.color)  # Рисует сжимающийся круг

    def is_clicked(self, pos):
        """ Вычисляет по формуле расстояния, пришелся ли клик мыши (pos) внутрь этого шарика """
        d = math.sqrt((self.x - pos[0]) ** 2 + (self.y - pos[1]) ** 2)
        return d <= self.radius  # Возвращает True, если расстояние до центра меньше или равно радиусу


# — Класс Game
class Game:
    def __init__(self):
        """ Конструктор класса игры: автоматически запускает начальную настройку при старте """
        self.setup_game()  # Вызывает метод инициализации параметров игры

    def setup_game(self):
        """ Сбрасывает и подготавливает все игровые переменные для начала новой игры """
        self.circles = []             # Создает пустой список для хранения активных шариков на экране
        self.score = 0                # Обнуляет текущий счет игрока
        self.speed_multiplier = 1.0   # Сбрасывает множитель скорости шариков до начального (1.0)
        self.game_over = False        # Устанавливает флаг окончания игры в положение "Ложь"
        # Выбирает случайное количество шариков для старта (в пределах заданных констант)
        count = random.randint(MIN_CIRCLES, MAX_CIRCLES)
        for _ in range(count):
            self.circles.append(self.spawn_circle())  # Создает новые шарики и добавляет их в список

    def spawn_circle(self):
        """ Создает и возвращает новый объект (экземпляр) класса Circle """
        return Circle()  # Возвращает готовый объект шарика со случайными свойствами

    def handle_click(self, pos):
        """ Обрабатывает клики мышкой по экрану и проверяет попадание по шарикам """
        if self.game_over:  # Проверяет флаг: если игра уже окончена
            return          # Выходит из метода, полностью игнорируя дальнейшие клики

        for circle in self.circles:
            # Если игрок кликнул по шарику и этот шарик еще не начал лопаться
            if circle.is_clicked(pos):
                circle.is_popping = True  # Переводит шарик в режим анимации лопания
                self.score += 1           # Увеличивает счет игрока на единицу
                # Увеличивает множитель скорости всех шариков на 10% за каждый лопнутый шарик
                self.speed_multiplier = 1 + self.score * 0.1

                if self.score >= MAX_SCORE:
                    self.game_over = True  # Если набрано 25 очков, включает режим окончания игры
                break  # Выходит из цикла, чтобы один клик не лопал несколько наложенных шариков

    def update(self):
        """ Управляет ежекадровым обновлением всей игровой логики и движением объектов """
        if self.game_over:  # Проверяет флаг: если игра окончена
            return          # Выходит из метода, замораживая все движения и изменения на экране

        new_circles = []  # Создает временный список для фильтрации выживших шариков
        popped = 0        # Счетчик шариков, которые окончательно завершили анимацию лопания в этом кадра
        for c in self.circles:
            if c.update():
                popped += 1  # Если метод update вернул True, шарик полностью исчез, увеличиваем счетчик
            else:
                new_circles.append(c)  # Если шарик целый или еще сжимается, сохраняем его в новый список
        self.circles = new_circles  # Обновляет основной список, удаляя из него исчезнувшие шарики

        # Спавнит новые шарики только если лимит еще не достигнут
        for _ in range(popped):
            self.circles.append(self.spawn_circle())  # Добавляет новый живой шарик взамен каждого удаленного

        for c in self.circles:
            c.move(self.speed_multiplier)  # Передвигает каждый шарик с учетом текущего множителя скорости

    def draw(self):
        """ Отвечает за отрисовку всего графического интерфейса и объектов на экране """
        screen.fill(BACKGROUND_COLOR)  # Очищает экран, полностью закрашивая его темно-синим цветом фона

        # Рисуем шарики только если игра продолжается
        if not self.game_over:
            for c in self.circles:
                c.draw()  # Вызывает метод отрисовки для каждого шарика из списка
            # Рисует текст-инструкцию для игрока по центру в нижней части экрана
            screen.draw.text('Нажимай левой кнопкой мыши на шарики, чтобы лопать их',
                             center=(WIDTH // 2, HEIGHT - 40), fontsize=24, color=HINT_TEXT_COLOR)
        else:
            # Экран окончания игры: выводится, если набрано 25 очков
            # Рисует большую красную надпись "ИГРА ОКОНЧЕНА!" по центру экрана с черным контуром в 1 пиксель
            screen.draw.text('ИГРА ОКОНЧЕНА!',
                             center=(WIDTH // 2, HEIGHT // 2 - 20), fontsize=50, color=GAMEOVER_TEXT_COLOR, owidth=1,
                             ocolor=(0, 0, 0))
            # Рисует подзаголовок с финальным победным результатом игрока
            screen.draw.text(f'Вы успешно лопнули {MAX_SCORE} шариков!',
                             center=(WIDTH // 2, HEIGHT // 2 + 30), fontsize=30, color=TEXT_COLOR)

        # Общие элементы интерфейса, которые отображаются на экране всегда
        # Выводит текущий счет игрока в верхнем левом углу экрана
        screen.draw.text(f'Счет: {self.score}',
                         topleft=(20, 20), fontsize=30, color=TEXT_COLOR)
        # Выводит текущий показатель скорости игры в верхнем правом углу экрана
        screen.draw.text(f'Скорость: {self.speed_multiplier:.1f}',
                         topright=(WIDTH - 20, 20), fontsize=30, color=SECONDARY_TEXT_COLOR)
        # Выводит системную подсказку по клавишам управления в самой нижней точке по центру
        screen.draw.text('R - новая игра | ESC - выход',
                         center=(WIDTH // 2, HEIGHT - 15), fontsize=20, color=HELP_TEXT_COLOR)


# — Pygame Zero хуки —
game = Game()  # Создает глобальный управляющий объект игры на основе класса Game


def update():
    """ Главная функция обновления Pygame Zero: автоматически вызывается движком около 60 раз в секунду """
    game.update()  # Перенаправляет вызов в метод update нашего игрового объекта


def draw():
    """ Главная функция отрисовки Pygame Zero: автоматически вызывается движком для перерисовки экрана """
    game.draw()  # Перенаправляет вызов в метод draw нашего игрового объекта


